-- 10. 연차 잔여 (2026년) — 직원 15명 × 1행
-- 근로기준법 제60조: 1년차 11일 / 2년차 15일 / 3년차+ 15+floor((years-1)/2), ≤25
-- 사용일수는 0~12일 사이 랜덤.
-- ═══════════════════════════════════════════════════════════
do $$
declare
  emp record;
  years int;
  granted numeric(5,1);
  used numeric(5,1);
begin
  for emp in select id, hire_date from employees loop
    years := extract(year from age(date '2026-01-01', emp.hire_date))::int;
    if years < 1 then
      granted := 11;
    elsif years = 1 then
      granted := 15;
    else
      granted := least(25, 15 + floor((years - 1)::numeric / 2));
    end if;
    used := round((random() * least(granted::numeric, 12))::numeric, 1);
    insert into leave_balances (employee_id, year, total_granted, total_used, remaining)
    values (emp.id, 2026, granted, used, granted - used);
  end loop;
end;
$$;

